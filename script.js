function buildQuiz() {
  var h = QZ.map(function (q, i) {
    return '<fieldset class="q"><legend>' + (i + 1) + '. ' + q[0] +
      '</legend>' + q[1].map(function (o, j) {
        return '<label><input type="radio" name="q' + i + '" id="q' +
          i + '_' + j + '" value="' + o[1].join(",") +
          '"><span>' + o[0] + '</span></label>';
      }).join("") + '</fieldset>';
  }).join("");

  h += '<div class="btns"><button class="btn" type="submit">Ver resultado</button></div>';
  $("#quizForm").innerHTML = h;

  $("#quizForm").addEventListener("submit", function (e) {
    e.preventDefault();

    var score = {};
    var any = false;

    QZ.forEach(function (q, i) {
      var s = document.querySelector('input[name="q' + i + '"]:checked');

      if (s) {
        any = true;

        s.value.split(",").forEach(function (id) {
          score[id] = (score[id] || 0) + 1;
        });
      }
    });

    if (!any) {
      $("#quizOut").innerHTML = '<p class="note">Responda ao menos uma pergunta.</p>';
      return;
    }

    var best = C[0];
    var m = -1;

    C.forEach(function (c) {
      if ((score[c.id] || 0) > m) {
        m = score[c.id] || 0;
        best = c;
      }
    });

    $("#quizOut").innerHTML =
      '<div class="result" style="--k:' + best.cor + '">' +
      '<p class="mono">Sua tropa</p><h3>' + best.nome + '</h3>' +
      '<p style="margin:8px 0 0">' + best.lead + '</p>' +
      '<div class="btns"><button class="btn" type="button" id="goBtn" style="background:' +
      best.cor + ';color:' + best.on + '">Abrir ' + best.nome +
      '</button></div></div>';

    $("#goBtn").addEventListener("click", function () {
      pick(best.id, true);
    });
  });
}

